import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

const outputDirectory = path.resolve('dist');

async function listFiles(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relative = path.posix.join(prefix, entry.name);
    if (relative === 'sw.js' || relative === '_headers' || relative.startsWith('.vite/')) continue;
    // Keep uncompressed working copies out of the precache. Published slider
    // banners use the optimized JPEG files under public/slider-banners.
    if (relative.startsWith('slider-banners/') && relative.endsWith('.png')) continue;
    if (entry.isDirectory()) files.push(...await listFiles(path.join(directory, entry.name), relative));
    else files.push(relative);
  }
  return files;
}

const files = (await listFiles(outputDirectory)).sort();
const deferredChunk = /\/assets\/(?:AdminDashboard|AddServiceModal|SuggestionsFeedModal|SmartSearchModal|AppVersionModal|JobsPage|JobDetailPage|JobSlideView)-/;
const appShellFiles = files.filter(file => !deferredChunk.test(`/${file}`));
const digest = createHash('sha256');
digest.update(await readFile(new URL(import.meta.url)));
for (const file of files) {
  const details = await stat(path.join(outputDirectory, file));
  digest.update(`${file}:${details.size}\n`);
  if (!/[-.][A-Za-z0-9_-]{8,}\.(?:js|css)$/.test(file)) digest.update(await readFile(path.join(outputDirectory, file)));
}
const version = digest.digest('hex').slice(0, 16);

const source = `/* Generated by scripts/build-service-worker.mjs. */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = 'wisal-shell-' + VERSION;
const MEDIA_CACHE = 'wisal-media-' + VERSION;
const CACHE_PREFIXES = ['wisal-shell-', 'wisal-media-'];
const APP_SHELL = ${JSON.stringify(appShellFiles.map(file => `./${file}`))};
const INDEX_URL = new URL('./index.html', self.registration.scope).href;

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    await cache.add(new Request('./index.html', { cache: 'reload' }));
    await Promise.allSettled(APP_SHELL.filter(url => url !== './index.html').map(url => cache.add(new Request(url, { cache: 'reload' }))));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter(name => CACHE_PREFIXES.some(prefix => name.startsWith(prefix)) && ![SHELL_CACHE, MEDIA_CACHE].includes(name)).map(name => caches.delete(name)));
    await self.clients.claim();
  })());
});

async function networkFirstNavigation(request, event) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(INDEX_URL);
  const network = fetch(request).then(async response => {
    if (response.ok) await cache.put(INDEX_URL, response.clone());
    return response;
  });
  if (!cached) return network.catch(() => Response.error());
  event.waitUntil(network.catch(() => undefined));
  const safeNetwork = network.catch(() => cached);
  const timeout = new Promise(resolve => setTimeout(() => resolve(cached), 2500));
  return Promise.race([safeNetwork, timeout]);
}

async function cacheFirst(request) {
  const cache = await caches.open(SHELL_CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) await cache.put(request, response.clone());
  return response;
}

async function trimMediaCache(cache, maximum = 80) {
  const keys = await cache.keys();
  await Promise.all(keys.slice(0, Math.max(0, keys.length - maximum)).map(key => cache.delete(key)));
}

async function staleWhileRevalidateMedia(request, event) {
  const cache = await caches.open(MEDIA_CACHE);
  // Images may have been precached with the app shell (local slider assets)
  // or discovered at runtime (Supabase/Storage assets). Prefer the runtime
  // copy, but keep the shell copy as an offline fallback as well.
  const shell = await caches.open(SHELL_CACHE);
  const cached = await cache.match(request) || await shell.match(request);
  const update = fetch(request).then(async response => {
    if (response.ok || response.type === 'opaque') {
      await cache.put(request, response.clone());
      await trimMediaCache(cache);
    }
    return response;
  });
  if (cached) {
    event.waitUntil(update.catch(() => undefined));
    return cached;
  }
  return update;
}

function isPrivateOrSignedMediaRequest(request, url) {
  const query = (url.search + url.hash).toLowerCase();
  return Boolean(
    url.pathname.includes('/complaint-media/') ||
    url.pathname.includes('/storage/v1/object/sign/') ||
    /(?:^|[?&#])(token|signature|expires|download|signedurl)=/.test(query) ||
    request.headers.has('authorization')
  );
}

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (request.mode === 'navigate') {
    event.respondWith(networkFirstNavigation(request, event));
    return;
  }
  if (request.destination === 'image') {
    if (isPrivateOrSignedMediaRequest(request, url)) {
      // Private complaint media and signed storage URLs are network-only.
      // Never read or write them from a browser cache.
      event.respondWith(fetch(new Request(request, { cache: 'no-store' })));
      return;
    }
    event.respondWith(staleWhileRevalidateMedia(request, event));
    return;
  }
  if (url.origin === self.location.origin && url.href.startsWith(self.registration.scope)) {
    event.respondWith(cacheFirst(request));
    return;
  }
});
`;

await writeFile(path.join(outputDirectory, 'sw.js'), source, 'utf8');
console.log(`[service-worker] ${appShellFiles.length} core files precached as ${version}; optional chunks cache on use`);
