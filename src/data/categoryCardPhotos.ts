export function getCategoryCardPhoto(slug: string, childSlug?: string): string | undefined {
  const file = (childSlug ? CHILD_PHOTOS[slug + '--' + childSlug] : undefined) ?? PHOTO_FILES[slug];
  if (!file) return undefined;
  const base = (import.meta as ImportMeta & { env?: { BASE_URL?: string } }).env?.BASE_URL ?? './';
  return base + file;
}
