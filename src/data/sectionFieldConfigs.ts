/** إعداد خدمة مهنية مع حقولها المشتركة وبيانات طبيعتها. */
function service(subject: string, profession: string, specialtyLabel: string, specialties: string[], detailsHint: string): SectionFieldConfig {
  return {
    nameLabel: `اسم ${subject}`, namePlaceholder: `اكتب اسم ${subject}`,
    profession, professionLabel: specialtyLabel,
    experienceLabel: 'نبذة ووصف الخدمة', experiencePlaceholder: detailsHint,
    locationLabel: 'العنوان والمنطقة', phoneLabel: 'رقم التواصل',
    registration: reg([txt('serviceType', specialtyLabel, `مثال: ${specialties[0]}`)], { descriptionLabel: 'الوصف', descriptionPlaceholder: detailsHint }),
    specialties,
  };
}

/** إعداد متجر/منتج؛ يستخدم النموذج الديناميكي ذاته ولا يضيف أي تخزين جديد. */
function product(subject: string, profession: string, specialtyLabel: string, specialties: string[], detailsHint: string): SectionFieldConfig {
  return service(subject, profession, specialtyLabel, specialties, detailsHint);
}
