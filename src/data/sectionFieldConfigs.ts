import type { SectionFieldConfig, SectionRegistrationConfig } from '../types/models';

/**
 * إعدادات حقول الانضمام لأقسام الواجهة (Directory sections) التي لا يقابلها
 * صف في جدول categories — أي التي كانت ترجع للإعداد العام GENERIC_FIELD_CONFIG.
 * -----------------------------------------------------------------------------
 * • لا يُنشئ هذا الملف أي قسم في قاعدة البيانات ولا يغيّر أي slug أو ID.
 * • كل قسم يمتلك إعداد fields مناسباً لطبيعته: تسميات الحقول، المهنة الافتراضية،
 *   التخصصات (تطابق أسماء التصنيفات الفرعية)، وحقول التسجيل المخصّصة.
 * • الحقول المشتركة (المحافظة، المنطقة، الوصف، الصور 1–5، والهاتف) تُبنى عبر reg()
 *   فتظهر في كل الأقسام دون تكرار.
 * • التصنيفات الفرعية (children) ترث إعداد قسمها الأب تلقائياً لأن نموذج الانضمام
 *   واحد وديناميكي، ويُعبّأ التخصص من الفرع المختار.
 */

type RegField = SectionRegistrationConfig['fields'][number];

const gov = (): RegField => ({ key: 'governorate', label: 'المحافظة', placeholder: 'مثال: بغداد', type: 'text', required: true });
const area = (label = 'المنطقة', ph = 'المنطقة، الشارع، وأقرب نقطة دالة'): RegField => ({ key: 'area', label, placeholder: ph, type: 'text', required: true });
const exp = (): RegField => ({ key: 'experienceYears', label: 'سنوات الخبرة', placeholder: 'مثال: 5', type: 'number', required: true, min: 0 });
const feat = (label = 'الوصف', ph = 'اذكر ما يميز خدمتك وما تقدمه.'): RegField => ({ key: 'features', label, placeholder: ph, type: 'textarea', required: true });
const txt = (key: string, label: string, ph: string): RegField => ({ key, label, placeholder: ph, type: 'text', required: true });
const att = (key: string, label: string, ph: string): RegField => ({ key, label, placeholder: ph, type: 'text', required: true, attachment: true });

/** حقل تسجيل مخصّص + الحقول المشتركة (محافظة/منطقة/خبرة/وصف) + الصور + الهاتف. */
function reg(customFields: RegField[], opts: {
  phoneRequired?: boolean; minImages?: number; maxImages?: number; includeExperience?: boolean;
  descriptionLabel?: string; descriptionPlaceholder?: string;
} = {}): SectionRegistrationConfig {
  const shared: RegField[] = [gov(), area()];
  if (opts.includeExperience !== false) shared.push(exp());
  shared.push(feat(opts.descriptionLabel, opts.descriptionPlaceholder));
  return {
    phoneRequired: opts.phoneRequired ?? true,
    images: { min: opts.minImages ?? 1, max: opts.maxImages ?? 5 },
    fields: [...customFields, ...shared],
  };
}

